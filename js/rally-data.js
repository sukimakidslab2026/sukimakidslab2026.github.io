/*
 * スタンプラリーの設定データ（運営者が編集するファイル）
 *
 * ここに書いた内容が、スタンプラリー画面の「掲示板のある場所」などに表示されます。
 * Supabaseの接続設定（js/config.js）とは別のファイルです。秘密の情報は書かないでください。
 *   ※ 掲示板のQRコードの文字列（合言葉）は、ここには書きません（公開されてしまうため）。
 *     QRコードは scripts/make_boards.py で作り、サーバー（Supabase）に登録します（README 参照）。
 *
 * 【場所を入力する前に確認してください】
 *   場所を公開して問題ないかを、運営側で確認したうえで入力してください。
 *   何も入力していないときは、「掲示板の場所は、準備ができしだい、ここに表示されます。」と表示され、地図のリンクも出ません。
 */

// 景品に関する、参加者への補足（空のままなら表示されません）
// 例：「景品がなくなり次第、終了します」「受け取り方法は、アンケート送信後にご案内します」
// ※ 在庫・条件を運営側で確認してから入力してください。条件を達成したことと、景品を受け取れることは別です。
window.RALLY_PRIZE = {
  notice: ""
};

// 掲示板のある場所（複数登録できます。{ … } を , で区切って並べます）
//   name        ：場所の名前（例：「◯◯公園」「△△商店街の入口」）
//   description ：場所の簡単な説明（例：「入口の掲示板です」）
//   address     ：住所（座標を入力した場合は、座標が優先されます）
//   lat, lng    ：緯度・経度（数字）。Googleマップで場所を右クリック（スマートフォンは長押し）すると、
//                 「35.69…, 139.77…」のように表示されるので、前が緯度、後ろが経度です。
//   mapQuery    ：Googleマップで探すための言葉（施設名など）。住所の代わりに使えます。
// 住所・座標・mapQuery のどれも入っていない場所には、地図のリンクを出しません（推測で場所を決めません）。
// ★仮の場所：確認用に、座標（35°41'36.2"N 139°46'47.1"E）を1か所だけ入れています。
//   実際の場所が決まったら、書き換えてください（場所ごとに { … } を増やせます）。
window.RALLY_PLACES = [
  { name: "（仮）掲示板のある場所", description: "", address: "", lat: 35.693389, lng: 139.77975, mapQuery: "" }
];

// 地図の埋め込み（Googleマップ）を使うか。使わないときは false
window.RALLY_PLACES_PREVIEW = true;
// true：地図を最初から表示する（押さなくても見える。画面の近くまで来たときに読み込みます）。
// false：「地図を表示」を押したときだけ読み込む
window.RALLY_PLACES_PREVIEW_OPEN = true;

// すべての掲示板を1枚にまとめた地図（Googleマイマップ）。掲示板が十数か所ある場合は、これを使うと分かりやすくなります。
//   作り方：Googleマイマップ（https://www.google.com/maps/d/）で、掲示板の場所にピンを立てた地図を作り、共有（リンクを知っている全員が閲覧可）にする。
//   RALLY_MAP_VIEW_URL  ：共有URL（https://www.google.com/maps/d/viewer?mid=…）→「すべての掲示板の地図を開く」ボタンを表示
//   RALLY_MAP_EMBED_URL ：埋め込みURL（https://www.google.com/maps/d/embed?mid=…）→ 画面に地図を埋め込んで表示
//     （マイマップの「︙」メニュー →「自分のサイトに埋め込む」で表示される、iframe の src の中のURLです）
window.RALLY_MAP_VIEW_URL = "";
window.RALLY_MAP_EMBED_URL = "";
